/**
 * The app's boot animation, as paths the site can draw: the monogram's centre line from
 * notteodo_monogram.dart (one loop in two halves, so two pens draw it at once, plus two tails),
 * and the traced wordmark split into its eight letters, so they can rise one by one.
 *
 *   pnpm tsx scripts/sync-pens.ts [--check]
 */
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { appFile, CHECK, emit, requireApp, ROOT } from "./lib/sync-util";

if (!requireApp("sync-pens")) process.exit(0);
const dart = appFile("frontend/lib/core/brand/notteodo_monogram.dart");
if (!dart) throw new Error("notteodo_monogram.dart not found in the app");

/** One `const List<List<double>> name = [...]` of cubic segments as an SVG path. */
function pen(name: string) {
  const start = dart!.indexOf(`const List<List<double>> ${name} = [`);
  if (start < 0) throw new Error(`${name} not found`);
  const body = dart!.slice(start, dart!.indexOf("];", start));
  const segs = [...body.matchAll(/\[\s*([-\d.,\s]+)\]/g)].map((m) => m[1]!.split(",").map(Number));
  return `M${segs[0]![0]} ${segs[0]![1]}` + segs.map((s) => `C${s.slice(2).join(" ")}`).join("");
}

/** The wordmark's subpaths, grouped into letters (a counter joins the letter around it). */
function letters() {
  const src = readFileSync(resolve(ROOT, "src/components/brand/logo-paths.ts"), "utf8");
  const d = /LOGO_WORDMARK = \{ d: "([^"]+)"/.exec(src)?.[1];
  if (!d) throw new Error("LOGO_WORDMARK not found");
  const boxes = d
    .split(/(?=M)/)
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => {
      const n = s.replace(/[MCLZz,]/g, " ").trim().split(/\s+/).map(Number);
      const xs = n.filter((_, i) => i % 2 === 0);
      const ys = n.filter((_, i) => i % 2 === 1);
      const x0 = Math.min(...xs);
      const x1 = Math.max(...xs);
      return { s, x0, x1, area: (x1 - x0) * (Math.max(...ys) - Math.min(...ys)) };
    })
    .sort((a, b) => b.area - a.area);
  const groups: { x0: number; x1: number; parts: string[] }[] = [];
  for (const b of boxes) {
    const g = groups.find((g) => b.x0 >= g.x0 - 2 && b.x1 <= g.x1 + 2);
    if (g) g.parts.push(b.s);
    else groups.push({ x0: b.x0, x1: b.x1, parts: [b.s] });
  }
  return groups.sort((a, b) => a.x0 - b.x0).map((g) => g.parts.join(" "));
}

const word = letters();
if (word.length !== 8) throw new Error(`expected 8 letters in the wordmark, found ${word.length}`);
const ts = `// Generated by scripts/sync-pens.ts from the app's monogram and the traced wordmark. Do not edit.
/** The monogram's centre line in the app's 100×100 box: two loop halves (two pens) and two tails. */
export const PEN_PATHS = ${JSON.stringify({ loops: [pen("_loopWest"), pen("_loopEast")], tails: [pen("_tailNorth"), pen("_tailSouth")] })} as const;
/** The app's stroke width in the same box. */
export const PEN_WIDTH = 4.1;
/** LOGO_WORDMARK, one path per letter: N O T t E o d o. */
export const WORDMARK_LETTERS = ${JSON.stringify(word)} as const;
`;
const ok = emit("src/components/brand/pen-paths.ts", ts);
if (CHECK && !ok) process.exit(1);
