/** Writes the CSP hash of the inline theme script so the strict CSP allows exactly that script. */
import { createHash } from "node:crypto";
import { emit } from "./lib/sync-util";
import { themeScript } from "../src/lib/theme-script";

const hash = `sha256-${createHash("sha256").update(themeScript).digest("base64")}`;
emit("src/lib/theme-script-hash.ts", `// Generated by scripts/hash-theme-script.ts. Do not edit.\nexport const THEME_SCRIPT_HASH = "${hash}";\n`);
