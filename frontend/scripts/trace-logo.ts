/**
 * Traces the app's official logo PNGs into exact vector outlines, so the site's monogram and
 * wordmark are the real logo rather than a redrawing. Output is single-colour (currentColor).
 *
 *   pnpm tsx scripts/trace-logo.ts [--check]
 */
import { readFileSync } from "node:fs";
import sharp from "sharp";
// @ts-expect-error potrace ships no types
import potrace from "potrace";
import { APP_DIR, CHECK, emit, requireApp } from "./lib/sync-util";

if (!requireApp("trace-logo")) process.exit(0);
const IMG = `${APP_DIR}/assets/images`;

async function crop(file: string, box?: { left: number; top: number; width: number; height: number }) {
  let img = sharp(readFileSync(file)).flatten({ background: "#ffffff" }).greyscale();
  if (box) img = img.extract(box);
  return img.png().toBuffer();
}

function trace(buf: Buffer): Promise<{ d: string; w: number; h: number }> {
  return new Promise((resolve, reject) => {
    const p = new potrace.Potrace({ threshold: 150, turdSize: 20, optTolerance: 0.25, alphaMax: 1 });
    p.loadImage(buf, (err: Error | null) => {
      if (err) return reject(err);
      const svg: string = p.getSVG();
      const d = /\sd="([^"]+)"/.exec(svg)?.[1] ?? "";
      const w = Number(/width="(\d+)"/.exec(svg)?.[1]);
      const h = Number(/height="(\d+)"/.exec(svg)?.[1]);
      resolve({ d: d.replace(/\s+/g, " ").trim(), w, h });
    });
  });
}

/** Tightly bounds the dark pixels so the viewBox hugs the artwork. */
async function bounds(buf: Buffer) {
  const { data, info } = await sharp(buf).raw().toBuffer({ resolveWithObject: true });
  let x0 = info.width, y0 = info.height, x1 = 0, y1 = 0;
  for (let y = 0; y < info.height; y++)
    for (let x = 0; x < info.width; x++)
      if (data[(y * info.width + x) * info.channels]! < 150) {
        if (x < x0) x0 = x;
        if (x > x1) x1 = x;
        if (y < y0) y0 = y;
        if (y > y1) y1 = y;
      }
  const pad = 4;
  return { left: Math.max(0, x0 - pad), top: Math.max(0, y0 - pad), width: x1 - x0 + pad * 2, height: y1 - y0 + pad * 2 };
}

async function traceTight(file: string, region?: { left: number; top: number; width: number; height: number }) {
  const base = await crop(file, region);
  const b = await bounds(base);
  const tight = await sharp(base).extract(b).png().toBuffer();
  return { ...(await trace(tight)), focus: await focus(tight) };
}

/**
 * The point deepest inside the ink (farthest from any paper), nearest the centre. The intro zooms
 * through the logo around this point, so the ribbon there grows to fill the screen.
 */
async function focus(buf: Buffer): Promise<[number, number]> {
  const { data, info } = await sharp(buf).raw().toBuffer({ resolveWithObject: true });
  const W = info.width, H = info.height;
  const dist = new Float32Array(W * H).fill(Infinity);
  const queue: number[] = [];
  for (let i = 0; i < W * H; i++)
    if (data[i * info.channels]! >= 150) {
      dist[i] = 0;
      queue.push(i);
    }
  for (let q = 0; q < queue.length; q++) {
    const i = queue[q]!;
    const x = i % W, y = (i / W) | 0;
    for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]] as const) {
      const nx = x + dx, ny = y + dy;
      if (nx < 0 || ny < 0 || nx >= W || ny >= H) continue;
      const j = ny * W + nx;
      if (dist[j]! > dist[i]! + 1) {
        dist[j] = dist[i]! + 1;
        queue.push(j);
      }
    }
  }
  let best = 0, bx = W / 2, by = H / 2;
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++) {
      const score = dist[y * W + x]! - 0.01 * Math.hypot(x - W / 2, y - H / 2);
      if (score > best) [best, bx, by] = [score, x, y];
    }
  return [bx, by];
}

// The monogram from the standalone N; the lettering from the lockup (the band below the N).
const mono = await traceTight(`${IMG}/notteodo_n_logo.png`);
const word = await traceTight(`${IMG}/notteodo_logo.png`, { left: 100, top: 620, width: 824, height: 180 });

const ts = `// Generated by scripts/trace-logo.ts from the app's logo PNGs. Do not edit.
/** The ribbon N, traced from assets/images/notteodo_n_logo.png (filled outline, even-odd). */
export const LOGO_MONOGRAM = { d: ${JSON.stringify(mono.d)}, w: ${mono.w}, h: ${mono.h}, focus: [${mono.focus}] } as const;
/** "NOTtEodo" lettering, traced from assets/images/notteodo_logo.png. */
export const LOGO_WORDMARK = { d: ${JSON.stringify(word.d)}, w: ${word.w}, h: ${word.h} } as const;
`;
const svg = (p: { d: string; w: number; h: number }, fill: string) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${p.w} ${p.h}"><path fill="${fill}" fill-rule="evenodd" d="${p.d}"/></svg>\n`;

const ok = [
  emit("src/components/brand/logo-paths.ts", ts),
  emit("public/logo-monogram.svg", svg(mono, "#1D1C15")),
  emit("public/logo-wordmark.svg", svg(word, "#1D1C15")),
].every(Boolean);
if (CHECK && !ok) process.exit(1);
console.log(`monogram ${mono.w}×${mono.h} (focus ${mono.focus}), wordmark ${word.w}×${word.h}`);
